// Delivers the bundled adblock data to the NetworkProcess and exposes the
// resulting filter-list state to Settings, plus the per-site "turn off ad
// blocking here" exceptions behind the toolbar shield.
//
// This is the browser-side half of the split Brave draws between its component
// layer and the shields engine: WebKit owns the engine, the catalog parser, and
// list storage; the app owns *delivery* of the two data files — the scriptlet
// resource library and the filter list catalog — via the WKWebsiteDataStore
// adblock SPI. Brave delivers the same two files through Component Updater
// ("Brave Ad Block Resources Library" and "Brave Ad Block List Catalog"); with
// no component updater here they are generated by
// Tools/Scripts/update-adblock-resources, checked in, and bundled with the app.
//
// Neither file is persisted by WebKit, so both are re-sent on every launch. The
// per-list enabled state and the downloaded list texts are persisted in the
// data store's own config, so re-sending the catalog does not re-download
// anything or undo the user's choices.

import Foundation
import Observation
@_spi(Private) import WebKit
import WebKit_Private
import WebKit_Private.WKWebsiteDataStorePrivate
import os

@Observable
@MainActor
final class AdBlockModel {
    /// One user-facing filter list from the catalog.
    ///
    /// Hidden catalog entries are always-on with no toggle, so WebKit reports
    /// them but they are left out of `lists`.
    struct CatalogList: Identifiable, Hashable {
        let id: String
        let title: String
        let details: String
        let supportURL: URL?
        let languages: [String]
        let isEnabled: Bool
        let isDefaultEnabled: Bool
        let lastFetched: Date?
    }

    static let shared = AdBlockModel()

    private static let logger = Logger(
        subsystem: Bundle.main.bundleIdentifier ?? "org.webkit.NewBrowser",
        category: String(describing: AdBlockModel.self)
    )

    /// Brave force-updates its list components every 100 minutes on top of
    /// Component Updater's own cadence; match that here.
    private static let refreshInterval = Duration.seconds(100 * 60)

    private(set) var lists: [CatalogList] = []

    /// Number of always-on lists WebKit is compiling that `lists` does not
    /// show, so Settings can say so rather than appear to be missing lists.
    private(set) var hiddenListCount = 0

    /// True once the catalog has been delivered and read back at least once.
    private(set) var isLoaded = false

    /// Sites the user turned ad blocking off for, sorted for display.
    ///
    /// WebKit keys these on the site being visited — the top-level page's exact
    /// host, as Brave's Shields do — so an entry exempts everything loaded on
    /// that site's pages and nothing loaded on other sites.
    private(set) var allowlistedSites: [String] = []

    var isEnabled = false {
        didSet {
            // `adopt(isEnabled:)` is WebKit telling us what it already has; only
            // a real user change is worth sending back and recording as a choice.
            guard isEnabled != oldValue, !isAdoptingStoredState else {
                return
            }
            store._setAdBlockEnabled(isEnabled)
            UserDefaults.standard.set(true, forKey: AppStorageKeys.adBlockConfigured)
            Self.logger.log("ad blocking \(self.isEnabled ? "enabled" : "disabled", privacy: .public)")
        }
    }

    private let store = WKWebsiteDataStore.default()
    private var didActivate = false
    private var isAdoptingStoredState = false
    private var refreshTask: Task<Void, Never>?

    private init() {}

    // MARK: - Activation

    /// Sends the bundled resource library and catalog to the NetworkProcess.
    ///
    /// Also starts the periodic list refresh. Safe to call from every window;
    /// only the first call does the work, since all windows share the default
    /// data store.
    func activate() {
        guard !didActivate else {
            return
        }
        didActivate = true

        if let resourcesJSON = Self.bundledJSON(named: "resources") {
            store._setAdBlockResources(resourcesJSON)
        } else {
            Self.logger.error("no bundled resources.json; scriptlet and redirect rules will not resolve")
        }

        guard let catalogJSON = Self.bundledJSON(named: "list_catalog") else {
            Self.logger.error("no bundled list_catalog.json; no filter lists will load")
            return
        }
        store._setAdBlockCatalog(catalogJSON)

        // WebKit's master gate defaults off so that nothing blocks until an
        // embedder asks for it. This browser's whole point is to block, so turn
        // it on the first time we run — and thereafter respect whatever the
        // user last chose, which WebKit persists for us.
        if !UserDefaults.standard.bool(forKey: AppStorageKeys.adBlockConfigured) {
            isEnabled = true
        }

        Task {
            await reloadState()
            startPeriodicRefresh()
        }
    }

    // MARK: - List management

    func setList(_ list: CatalogList, enabled: Bool) {
        store._setAdBlockCatalogListEnabled(enabled, forUUID: list.id)
        Task {
            await reloadState()
        }
    }

    /// Re-downloads every enabled list now.
    func refreshLists() {
        store._refreshAdBlockCatalogLists()
        Task {
            await reloadState()
        }
    }

    // MARK: - Per-site exceptions

    /// The host ad blocking would be turned off for on `url`, or nil for pages
    /// that have no site to key on (blank pages, files, web archives).
    static func site(for url: URL?) -> String? {
        guard let url, let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https" else {
            return nil
        }
        // WebKit compares the canonical (lowercased, punycode) host.
        guard let host = url.host(percentEncoded: true)?.lowercased(), !host.isEmpty else {
            return nil
        }
        return host
    }

    func isBlocking(onSite site: String) -> Bool {
        !allowlistedSites.contains(site)
    }

    /// Turns ad blocking on or off for `site`.
    ///
    /// Returns once the NetworkProcess has applied the change, so a reload
    /// issued afterwards is filtered under the new setting.
    func setBlocking(_ isBlocking: Bool, onSite site: String) async {
        if isBlocking {
            store._removeAdBlockAllowlistHost(site)
            allowlistedSites.removeAll { $0 == site }
        } else {
            store._addAdBlockAllowlistHost(site)
            if !allowlistedSites.contains(site) {
                allowlistedSites.append(site)
                allowlistedSites.sort()
            }
        }
        Self.logger.log("ad blocking \(isBlocking ? "enabled" : "disabled", privacy: .public) on \(site, privacy: .private)")

        // The state read travels the same connection as the change, so its reply
        // also confirms the change has landed.
        await reloadState()
    }

    private func startPeriodicRefresh() {
        refreshTask?.cancel()
        refreshTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: Self.refreshInterval)
                guard !Task.isCancelled, let self else {
                    return
                }
                self.refreshLists()
            }
        }
    }

    // MARK: - State read-back

    /// Reads the whole adblock config back from the NetworkProcess.
    ///
    /// This is also how the enabled state is recovered after a relaunch or a
    /// NetworkProcess crash, since WebKit — not this model — owns the persisted
    /// value.
    func reloadState() async {
        let state = await store._getAdBlockState()

        adopt(isEnabled: state["enabled"] as? Bool ?? false)
        allowlistedSites = (state["allowlist"] as? [String] ?? []).sorted()

        guard let entries = state["catalogLists"] as? [[String: Any]] else {
            Self.logger.error("adblock state carried no catalogLists")
            return
        }

        var visible: [CatalogList] = []
        var hidden = 0

        for entry in entries {
            guard let id = entry["uuid"] as? String, let title = entry["title"] as? String else {
                continue
            }
            if entry["hidden"] as? Bool ?? false {
                hidden += 1
                continue
            }

            let lastFetched = entry["lastFetched"] as? Double ?? 0
            visible.append(
                CatalogList(
                    id: id,
                    title: title,
                    details: entry["desc"] as? String ?? "",
                    supportURL: (entry["supportURL"] as? String).flatMap(URL.init(string:)),
                    languages: entry["langs"] as? [String] ?? [],
                    isEnabled: entry["enabled"] as? Bool ?? false,
                    isDefaultEnabled: entry["defaultEnabled"] as? Bool ?? false,
                    // 0 is WebKit's "never fetched", not the Unix epoch.
                    lastFetched: lastFetched > 0 ? Date(timeIntervalSince1970: lastFetched) : nil
                )
            )
        }

        // Enabled lists first, then alphabetical, so the handful a user actually
        // has on stays at the top of a 54-row list.
        visible.sort {
            $0.isEnabled == $1.isEnabled
                ? $0.title.localizedStandardCompare($1.title) == .orderedAscending
                : $0.isEnabled
        }

        lists = visible
        hiddenListCount = hidden
        isLoaded = true
    }

    /// Takes on the value WebKit reports without echoing it straight back.
    ///
    /// `isEnabled`'s observer would otherwise send it again on every read-back.
    private func adopt(isEnabled value: Bool) {
        isAdoptingStoredState = true
        isEnabled = value
        isAdoptingStoredState = false
    }

    // MARK: - Bundled data

    private static func bundledJSON(named name: String) -> String? {
        // The Resources folder is a synchronized group, so whether the AdBlock
        // subdirectory survives into the bundle is Xcode's call; look both ways.
        let url =
            Bundle.main.url(forResource: name, withExtension: "json", subdirectory: "AdBlock")
            ?? Bundle.main.url(forResource: name, withExtension: "json")
        guard let url else {
            return nil
        }
        return try? String(contentsOf: url, encoding: .utf8)
    }
}
